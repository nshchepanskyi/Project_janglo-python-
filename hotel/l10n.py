def tr(key, **kwargs):
    lang_dict = TRANSLATIONS.get(CURRENT_LANG, {})
    text = lang_dict.get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


def set_lang(code):
    global CURRENT_LANG
    CURRENT_LANG = code


def toggle_lang():
    global CURRENT_LANG
    CURRENT_LANG = "uk" if CURRENT_LANG == "en" else "en"
